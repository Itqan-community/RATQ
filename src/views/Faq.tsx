export const FaqPage: React.FC = () => {
  const { i18n } = useTranslation();
  const isAr = i18n.language === 'ar';
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<string>('all');
  const [expandedId, setExpandedId] = useState<string | null>('f1');

  const filteredFaqs = FAQS.filter((faq) => {
    const matchesCat = selectedCategory === 'all' || faq.category === selectedCategory;
    const q = isAr ? faq.question_ar : faq.question_en;
    const a = isAr ? faq.answer_ar : faq.answer_en;
    const matchesSearch =
      searchTerm.trim() === '' ||
      q.toLowerCase().includes(searchTerm.toLowerCase()) ||
      a.toLowerCase().includes(searchTerm.toLowerCase());
    return matchesCat && matchesSearch;
  });

  return (
    <div className="container mx-auto px-4 py-12 max-w-4xl">
      <div className="text-center mb-12">
        <Badge variant="primary" className="mb-3">
          <HelpCircle className="w-3.5 h-3.5 me-1.5" />
          {isAr ? 'مركز الأسئلة الشائعة' : 'FAQ Center'}
        </Badge>
        <h1 className="text-3xl md:text-5xl font-extrabold text-fg tracking-tight mb-4">
          {isAr ? 'كيف يمكننا مساعدتك؟' : 'How can we help you?'}
        </h1>
        <p className="text-fg-muted text-lg max-w-2xl mx-auto">
          {isAr
            ? 'إجابات شاملة حول ميثاق النزاهة، شارات الإتقان، تراخيص البرمجيات، وإدارة الموارد التقنية.'
            : 'Clear answers on sacred text integrity, Itqan badge tiers, licensing, and API access.'}
        </p>
      </div>

      {/* Search & Categories */}
      <div className="space-y-4 mb-8">
        <div className="relative">
          <Search className="w-5 h-5 absolute start-3 top-1/2 -translate-y-1/2 text-fg-muted pointer-events-none" />
          <Input
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            placeholder={isAr ? 'ابحث في الأسئلة الشائعة...' : 'Search questions...'}
            className="ps-10 h-12 text-base"
          />
        </div>

        <div className="flex flex-wrap gap-2">
          {[
            { id: 'all', label_ar: 'الكل', label_en: 'All', icon: Layers },
            { id: 'sacred', label_ar: 'القرآن الكريم', label_en: 'Noble Quran', icon: BookOpen },
            { id: 'badges', label_ar: 'شارات الإتقان', label_en: 'Itqan Badges', icon: ShieldCheck },
            { id: 'keys', label_ar: 'المفاتيح والاستهلاك', label_en: 'Keys & Usage', icon: Key },
            { id: 'publishing', label_ar: 'النشر والتوثيق', label_en: 'Publishing', icon: HelpCircle },
          ].map((cat) => {
            const Icon = cat.icon;
            const active = selectedCategory === cat.id;
            return (
              <button
                key={cat.id}
                onClick={() => setSelectedCategory(cat.id)}
                className={`inline-flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg text-sm font-medium transition-all ${
                  active
                    ? 'bg-ratq-600 text-white shadow-sm'
                    : 'bg-canvas-card border border-border text-fg-muted hover:text-fg'
                }`}
              >
                <Icon className="w-4 h-4" />
                <span>{isAr ? cat.label_ar : cat.label_en}</span>
              </button>
            );
          })}
        </div>
      </div>

      {/* FAQ Accordion */}
      <div className="space-y-3">
        {filteredFaqs.length === 0 ? (
          <Card className="p-8 text-center text-fg-muted">
            {isAr ? 'لا توجد نتائج مطابقة لبحثك.' : 'No matching questions found.'}
          </Card>
        ) : (
          filteredFaqs.map((faq) => {
            const isExpanded = expandedId === faq.id;
            return (
              <Card
                key={faq.id}
                className="overflow-hidden transition-all duration-200 border-border"
              >
                <button
                  type="button"
                  onClick={() => setExpandedId(isExpanded ? null : faq.id)}
                  className="w-full p-5 text-start flex items-center justify-between gap-4 hover:bg-canvas-subtle/50 transition-colors"
                >
                  <span className="font-bold text-fg text-base md:text-lg">
                    {isAr ? faq.question_ar : faq.question_en}
                  </span>
                  <ChevronDown
                    className={`w-5 h-5 text-fg-muted shrink-0 transition-transform duration-200 ${
                      isExpanded ? 'rotate-180 text-ratq-600' : ''
                    }`}
                  />
                </button>
                {isExpanded && (
                  <div className="px-5 pb-5 pt-1 text-fg-muted leading-relaxed text-sm md:text-base border-t border-border/50">
                    {isAr ? faq.answer_ar : faq.answer_en}
                  </div>
                )}
              </Card>
            );
          })
        )}
      </div>

      {/* Support Box */}
      <div className="mt-12 p-8 rounded-2xl bg-canvas-card border border-border text-center">
        <h3 className="text-xl font-bold text-fg mb-2">
          {isAr ? 'لم تجد الإجابة التي تبحث عنها؟' : 'Still have questions?'}
        </h3>
        <p className="text-fg-muted text-sm mb-6 max-w-md mx-auto">
          {isAr
            ? 'فريق مجتمع رتق ومحكموه متاحون للإجابة عن استفساراتك الفنية والعلمية.'
            : 'Our community coordinators and technical reviewers are here to assist.'}
        </p>
        <Link to="/contact">
          <Button variant="primary">
            {isAr ? 'تواصل معنا' : 'Contact Support'}
          </Button>
        </Link>
      </div>
    </div>
  );
};

export default FaqPage;
